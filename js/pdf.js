/* ============================================================
   pdf.js — professional cooperative PDF generation
   Uses jsPDF + jspdf-autotable.
   ============================================================ */
'use strict';

ELF.pdf = (function () {
    const LOGO_URL = 'https://pub-cf11059ab3634dc1aadcd8682fc2dcc5.r2.dev/logo.png';
    let _logoCache = null;

    // ---------- LOGO (cached) ----------
    async function loadLogo() {
        if (_logoCache !== null) return _logoCache;
        try {
            _logoCache = await new Promise((resolve, reject) => {
                const img = new Image();
                img.crossOrigin = 'anonymous';
                img.onload = () => resolve(img);
                img.onerror = () => reject(new Error('logo load failed'));
                img.src = LOGO_URL;
            });
        } catch (e) {
            console.warn('[pdf] logo not available — continuing without it', e);
            _logoCache = false;
        }
        return _logoCache;
    }

    // ---------- HEADER ----------
    async function cooperativeHeader(doc, title, period) {
        const s = ELF.settings;
        const W = doc.internal.pageSize.getWidth();
        const brand = s['cooperative.name'] || 'ECOLE LA FONTAINE Staff Cooperative';

        // Green band
        doc.setFillColor(15, 81, 50);
        doc.rect(0, 0, W, 26, 'F');

        // Logo plate (white rounded square) — only if logo loaded
        const logo = await loadLogo();
        let textStartX = 14;
        if (logo) {
            try {
                doc.setFillColor(255, 255, 255);
                doc.roundedRect(14, 4, 18, 18, 3, 3, 'F');
                doc.addImage(logo, 'PNG', 15, 5, 16, 16);
                textStartX = 38;
            } catch (e) {
                console.warn('[pdf] addImage failed', e);
            }
        }

        // Cooperative name
        doc.setTextColor(255, 255, 255);
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(14);
        doc.text(brand, textStartX, 12);

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(9);
        doc.text('Cooperative Management System', textStartX, 18);

        // Right-side meta
        doc.setFontSize(8);
        if (s['cooperative.airtel']) doc.text('Airtel: ' + s['cooperative.airtel'], W - 14, 12, { align: 'right' });
        if (s['cooperative.address']) doc.text(s['cooperative.address'], W - 14, 18, { align: 'right' });

        // Report title
        doc.setTextColor(23, 37, 29);
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(15);
        doc.text(title, 14, 40);

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(9.5);
        doc.setTextColor(90, 100, 96);
        if (period) doc.text('Period: ' + period, 14, 46);
        doc.text('Generated: ' + new Date().toLocaleString(), W - 14, 46, { align: 'right' });

        const ref = (s['report.prefix'] || 'ELF') + '-' + Date.now().toString().slice(-8);
        doc.setFontSize(8);
        doc.text('Ref: ' + ref, 14, 52);
        doc.text('Prepared by: Secretary', W - 14, 52, { align: 'right' });

        doc.setDrawColor(220, 226, 222);
        doc.line(14, 56, W - 14, 56);
        return 62;
    }

    // ---------- FOOTER (applied to every page) ----------
    function footer(doc) {
        const W = doc.internal.pageSize.getWidth();
        const H = doc.internal.pageSize.getHeight();
        const total = doc.internal.getNumberOfPages();

        for (let i = 1; i <= total; i++) {
            doc.setPage(i);
            doc.setDrawColor(220, 226, 222);
            doc.line(14, H - 16, W - 14, H - 16);

            doc.setFontSize(8);
            doc.setTextColor(120, 130, 125);
            doc.text(
                ELF.settings['report.footer'] || 'Generated by ECOLE LA FONTAINE Staff Cooperative',
                14, H - 10
            );
            doc.text('Page ' + i + ' of ' + total, W - 14, H - 10, { align: 'right' });
        }
    }

    // ---------- GENERATE ----------
    /**
     * generate({ title, period, columns, rows, summary, orientation, notes })
     * columns: [{ header, dataKey, halign?, width? }]
     * Returns a jsPDF document object.
     */
    async function generate({ title, period, columns, rows, summary, orientation = 'portrait', notes }) {
        const { jsPDF } = window.jspdf;
        const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation });
        const top = await cooperativeHeader(doc, title, period);

        doc.autoTable({
            startY: top,
            head: [columns.map(c => c.header)],
            body: rows.map(r => columns.map(c => {
                const v = r[c.dataKey];
                return v === null || v === undefined ? '' : String(v);
            })),
            styles: {
                font: 'helvetica',
                fontSize: 8.5,
                cellPadding: 2.5,
                overflow: 'linebreak',
                valign: 'middle'
            },
            headStyles: {
                fillColor: [15, 81, 50],
                textColor: 255,
                fontStyle: 'bold',
                fontSize: 8.5
            },
            alternateRowStyles: { fillColor: [246, 248, 247] },
            columnStyles: columns.reduce((acc, c, i) => {
                acc[i] = { halign: c.halign || 'left', cellWidth: c.width || 'auto' };
                return acc;
            }, {}),
            margin: { left: 14, right: 14, top: 10, bottom: 20 }
        });

        let y = doc.lastAutoTable.finalY + 6;
        const W = doc.internal.pageSize.getWidth();

        if (summary && summary.length) {
            const boxH = 10 + summary.length * 6;
            doc.setFillColor(241, 244, 242);
            doc.roundedRect(14, y, W - 28, boxH, 2, 2, 'F');

            doc.setFontSize(10);
            doc.setFont('helvetica', 'bold');
            doc.setTextColor(23, 37, 29);
            doc.text('Summary', 18, y + 7);

            doc.setFont('helvetica', 'normal');
            doc.setFontSize(9);
            summary.forEach((s, i) => {
                doc.text(String(s.label), 18, y + 14 + i * 6);
                doc.text(String(s.value), W - 18, y + 14 + i * 6, { align: 'right' });
            });

            y += boxH + 6;
        }

        if (notes) {
            doc.setFontSize(8.5);
            doc.setTextColor(90, 100, 96);
            const lines = doc.splitTextToSize('Notes: ' + notes, W - 28);
            doc.text(lines, 14, y + 4);
        }

        footer(doc);
        return doc;
    }

    // ---------- PREVIEW ----------
    function preview(doc) {
        const url = doc.output('bloburl');
        window.open(url, '_blank');
    }

    // ---------- DOWNLOAD ----------
    function download(doc, filename) {
        doc.save(filename || ('elf-' + Date.now() + '.pdf'));
    }

    // ---------- PRESENT (preview modal + download button) ----------
    async function present(opts, filename) {
        const doc = await generate(opts);
        const url = doc.output('bloburl');

        const body = document.createElement('div');
        body.innerHTML = `
      <div style="font-size:13px;color:var(--text-2);margin-bottom:10px">
        PDF preview — <strong>${ELF.ui.escapeHtml(opts.title)}</strong>
      </div>
      <iframe src="${url}"
              style="width:100%;height:60vh;border:1px solid var(--border);border-radius:8px;background:#fff"></iframe>
    `;

        ELF.ui.openModal({
            title: 'PDF Preview',
            body,
            actions: [
                { label: 'Close' },
                { label: 'Download PDF', kind: 'primary', close: false, onClick: () => download(doc, filename) }
            ]
        });
    }

    return { generate, preview, download, present, loadLogo };
})();